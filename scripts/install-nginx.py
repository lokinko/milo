#!/usr/bin/env python3
"""Add only the Milo include to an existing matching Nginx server block."""
import argparse
import datetime
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
from urllib.parse import urlparse

TOKEN = re.compile(r'''\#[^\n]*|"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'|[{};]|[^\s{};\#]+''')
MARKER = '# Milo managed route'
SNIPPET = Path('/etc/nginx/snippets/milo.conf')

def server_blocks(text):
    tokens = [m for m in TOKEN.finditer(text) if not m.group().startswith('#')]
    stack, blocks = [], []
    for i, token in enumerate(tokens):
        if token.group() == '{':
            stack.append(('server' if i and tokens[i-1].group() == 'server' else 'other', i))
        elif token.group() == '}':
            if not stack:
                raise ValueError('Unbalanced Nginx braces')
            kind, opened = stack.pop()
            if kind == 'server':
                directives, current, depth = [], [], 0
                for item in tokens[opened+1:i]:
                    value = item.group()
                    if value == '{': depth += 1; current = []
                    elif value == '}': depth -= 1; current = []
                    elif depth == 0 and value == ';': directives.append(current); current = []
                    elif depth == 0: current.append(value.strip('\"\''))
                names = [name for parts in directives if parts and parts[0] == 'server_name' for name in parts[1:]]
                listens = [' '.join(parts[1:]) for parts in directives if parts and parts[0] == 'listen']
                blocks.append(dict(start=tokens[opened-1].start(), end=token.end(), close=token.start(), names=names, listens=listens))
    if stack: raise ValueError('Unbalanced Nginx braces')
    return blocks

def snippet(base_path, port):
    common = f'''    proxy_pass http://127.0.0.1:{port};
    proxy_http_version 1.1;
    proxy_set_header Host $host;
    proxy_set_header X-Real-IP $remote_addr;
    proxy_set_header X-Forwarded-For $remote_addr;
    proxy_set_header X-Forwarded-Proto $scheme;
    proxy_set_header Connection "";
    proxy_cache off;
    proxy_buffering off;
    proxy_read_timeout 60s;
    client_max_body_size 1m;
'''
    return f'# Generated by Milo deploy.sh; included inside the existing server block.\nlocation = {base_path} {{\n{common}}}\nlocation ^~ {base_path}/ {{\n{common}}}\n'

def nginx_files():
    result = subprocess.run(['nginx', '-T'], capture_output=True, text=True)
    if result.returncode:
        raise RuntimeError('Existing Nginx configuration failed validation:\n' + result.stderr)
    names = re.findall(r'^# configuration file (.+):\s*$', result.stdout, re.M)
    return list(dict.fromkeys(Path(name).resolve() for name in names if Path(name).is_file()))

def choose(files, host, port):
    candidates = []
    for path in files:
        text = path.read_text()
        for block in server_blocks(text):
            if host in block['names'] and any(re.search(r'(^|[:\s])' + str(port) + r'(\s|$)', listen) for listen in block['listens']):
                candidates.append((path, text, block))
    if len(candidates) != 1:
        raise RuntimeError(f'Expected one explicit server_name {host} on port {port}; found {len(candidates)}. Use --nginx-config with the correct existing HTTPS configuration. No Nginx changes made.')
    return candidates[0]

def add_include(text, block):
    current = text[block['start']:block['end']]
    if MARKER in current and f'include {SNIPPET};' in current:
        return text
    # Refuse to shadow an existing manually configured Milo location.
    for match in re.finditer(r'\blocation\s+(?:=\s+|\^~\s+)?([^\s{]+)', current):
        location = match.group(1)
        if location.rstrip('/') == ARGS.path:
            raise RuntimeError('A manual location already owns this path. Resolve it before automatic installation.')
    include = f'\n    {MARKER}\n    include {SNIPPET};\n'
    return text[:block['close']] + include + text[block['close']:]

def atomic(path, data, mode=0o644, owner=None):
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, name = tempfile.mkstemp(prefix='.milo-', dir=path.parent)
    try:
        with os.fdopen(fd, 'wb') as f: f.write(data)
        os.chmod(name, mode)
        if owner: os.chown(name, *owner)
        os.replace(name, path)
    finally:
        if os.path.exists(name): os.unlink(name)

def main(args):
    global ARGS
    ARGS = args
    origin = urlparse(args.origin)
    if origin.scheme not in ('https', 'http') or not origin.hostname or origin.path or origin.query or origin.fragment or origin.username or origin.password:
        raise ValueError('Use a plain HTTP(S) origin without a path')
    if origin.port not in (None, 443 if origin.scheme == 'https' else 80):
        raise ValueError('Automatic Nginx configuration supports standard HTTP/HTTPS ports only')
    if not re.fullmatch(r'/[a-zA-Z0-9_-]+(?:/[a-zA-Z0-9_-]+)*', args.path): raise ValueError('Invalid base path')
    if not 1024 <= args.port <= 65535: raise ValueError('Invalid application port')
    generated = snippet(args.path, args.port)
    local = Path('.deploy/nginx-milo.conf')
    atomic(local, generated.encode(), 0o600)
    if args.generate_only: return
    if args.config:
        subprocess.run(['nginx', '-t'], check=True, capture_output=True)
        files = [Path(args.config).resolve()]
    else: files = nginx_files()
    path, text, block = choose(files, origin.hostname, 443 if origin.scheme == 'https' else 80)
    if origin.scheme == 'https' and not any('ssl' in x.split() for x in block['listens']):
        raise RuntimeError('The selected Nginx server must already have TLS enabled.')
    updated = add_include(text, block)
    print(f'Nginx target: {path}; route: {args.path}; existing main site preserved.')
    if args.dry_run: return
    if os.geteuid() != 0: raise RuntimeError('Run with sudo to configure Nginx')
    old_snippet = SNIPPET.read_bytes() if SNIPPET.exists() else None
    stat = path.stat()
    stamp = datetime.datetime.now(datetime.timezone.utc).strftime('%Y%m%dT%H%M%S%fZ')
    backup = Path('.deploy/nginx-backups') / stamp
    backup.mkdir(parents=True, mode=0o700)
    atomic(backup / 'server.conf', text.encode(), 0o600)
    if old_snippet is not None: atomic(backup / 'snippet.conf', old_snippet, 0o600)
    try:
        atomic(SNIPPET, generated.encode())
        atomic(path, updated.encode(), stat.st_mode & 0o777, (stat.st_uid, stat.st_gid))
        subprocess.run(['nginx', '-t'], check=True)
        subprocess.run(['nginx', '-s', 'reload'], check=True)
    except Exception:
        atomic(path, text.encode(), stat.st_mode & 0o777, (stat.st_uid, stat.st_gid))
        if old_snippet is None: SNIPPET.unlink(missing_ok=True)
        else: atomic(SNIPPET, old_snippet)
        subprocess.run(['nginx', '-t'], check=False)
        subprocess.run(['nginx', '-s', 'reload'], check=False)
        raise RuntimeError('Nginx validation/reload failed; previous configuration restored.')
    print('Nginx validated and reloaded.')

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--origin', required=True)
    parser.add_argument('--path', required=True)
    parser.add_argument('--port', required=True, type=int)
    parser.add_argument('--config')
    parser.add_argument('--dry-run', action='store_true')
    parser.add_argument('--generate-only', action='store_true')
    try: main(parser.parse_args())
    except Exception as error:
        print(f'ERROR: {error}', file=__import__('sys').stderr)
        raise SystemExit(1)
